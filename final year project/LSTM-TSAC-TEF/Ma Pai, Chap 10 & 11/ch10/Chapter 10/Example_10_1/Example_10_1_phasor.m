% The phasor is the second components of mag and angle 

% set up a table for 59.9 Hz

t_more = [0:1/1440:(23+24)/1440];
X_mag = [];
X_phase = [];
for i = 1:24
  x = cos(2*pi*59.9*(t_more(i:i+23)) + pi/3);
  X_phasor = fft(x);
  X_mag = [X_mag abs(X_phasor(2))];
  X_phase = [X_phase angle(X_phasor(2))*180/pi];
end
X_mag = X_mag/(24/2)/sqrt(2)
X_phase
figure, polar(X_phase*pi/180,X_mag)

