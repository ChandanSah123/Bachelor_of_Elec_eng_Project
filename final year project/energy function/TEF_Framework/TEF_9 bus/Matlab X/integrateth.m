dy(3)=Pm(3)-real(Y1(3,3))*(E(3)^2)-(C(3,1)*sin(y(3)-y(1))+D(3,1)*cos(y(3)-y(1))+C(3,2)*sin(y(3)-y(2))+D(3,2)*cos(y(3)-y(2)))-(H(3)/sum(H))*(Pm(1)-real(Y1(1,1))*(E(1)^2)+Pm(2)-real(Y1(2,2))*(E(2)^2)+Pm(3)-real(Y1(3,3))*(E(3)^2)-2*(D(1,2)*cos(y(1)-y(2))+D(1,3)*cos(y(1)-y(3))+D(2,3)*cos(y(2)-y(3))));
end