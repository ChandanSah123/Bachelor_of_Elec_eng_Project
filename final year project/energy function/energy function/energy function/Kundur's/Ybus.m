   15 4 0 0.0333 0];
 Y1=zeros(15,15);
% l=6;
% Z(l,3:4)=Z(l,3:4)*2;
% Z(l,5)=Z(l,5)/2;
for k=1:14
    zl=Z(k,3)+1i*Z(k,4);
    Y1(Z(k,1),Z(k,2))=-(1/zl);
    Y1(Z(k,2),Z(k,1))=-(1/zl);
    Y1(Z(k,1),Z(k,1))=Y1(Z(k,1),Z(k,1))+(1/zl)+1i*Z(k,5);
    Y1(Z(k,2),Z(k,2))=Y1(Z(k,2),Z(k,2))+(1/zl)+1i*Z(k,5);
end
Y1(7,7)=Y1(7,7)+(9.67/(0.9611^2))-1i*(-1/(0.9611^2));
Y1(9,9)=Y1(9,9)+(17.67/(0.9715^2))-1i*(-2.5/(0.9715^2));
Ynn=Y1(12:15,12:15); 
Ynr=Y1(12:15,1:11); 
Yrn=Y1(1:11, 12:15); 
Yrr=Y1(1:11,1:11);
% Ynn=Y1(1:4,1:4); 
% Ynr=Y1(1:4,5:11); 
% Yrn=Y1(5:11,1:4); 
% Yrr=Y1(5:11,5:11);
Yred=Ynn-((Ynr/Yrr)*Yrn);
Y1=Yred;
v=[1.11337 1.111908 1.11164 1.10127];
% v=[1.03 1.01 1.03 1.01];
th=data(100,1:4)*pi/180;
% th=[20.20 10.43 -6.91 -17.09];
for k=1:4
   Vn(k)=v(k)*(cos(th(k))+1i*sin(th(k))); 
end
Pe=[0 0 0 0;0 0 0 0];
for k=1:g
    Pe(2,k)=(real(Yred(k,k))*(abs(Vn(k)))^2);
    for n=1:g
        if k~=n
            Pe(2,k)=Pe(2,k)+abs(Vn(k))*abs(Vn(n))*abs(Yred(k,n))*cos(angle(Vn(k))-angle(Vn(n))-angle(Yred(k,n)));
        end
    end
end
Pe(1,:)=data(100,5:8);
